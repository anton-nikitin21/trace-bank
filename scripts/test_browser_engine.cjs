// Exercise the actual inline browser engine, not a copied implementation.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const { webcrypto } = require('node:crypto');
const html = fs.readFileSync(path.join(__dirname, '../templates/workspace.html'), 'utf8');
const blocks = [...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi)].map(match => match[1]);
const fixtures = blocks.find(code => code.startsWith('window.INITIAL_PACKET='));
const engine = blocks.find(code => code.includes('async function localApi('));
assert.ok(fixtures && engine, 'Browser fixtures and adapter must be present');
const context = vm.createContext({window:{}, crypto:webcrypto, TextEncoder, structuredClone});
vm.runInContext(fixtures, context);
vm.runInContext(engine, context);
(async () => {
  const initial = await vm.runInContext("localApi('/api/analyze', window.INITIAL_PACKET)",context);
  const corrected = await vm.runInContext("localApi('/api/analyze', window.CORRECTED_PACKET)",context);
  assert.equal(initial.issue_count,4);
  assert.equal(corrected.issue_count,0);
  assert.equal(corrected.rows.filter(row=>row.status==='complete').length,3);
  await assert.rejects(vm.runInContext(`localApi('/api/approve',{revision:${JSON.stringify(initial.revision)},comment:'Reviewed synthetic packet'})`,context),/замечания/);
  const shared = structuredClone(context.window.CORRECTED_PACKET);
  const [first,second] = shared.transactions;
  for(const doc of shared.documents)doc.text=doc.text.replace('Договор: '+second.contract,'Договор: '+first.contract);
  second.contract=first.contract;
  context.shared=shared;
  assert.equal((await vm.runInContext('analyzeDemo(shared)',context)).issue_count,0);
  shared.documents=shared.documents.filter(doc=>!(doc.text.includes('Тип: Акт')&&doc.text.includes(second.inn)));
  const separate=await vm.runInContext('analyzeDemo(shared)',context);
  assert.equal(separate.issue_count,1);
  assert.equal(separate.issues[0].inn,second.inn);
  assert.equal(separate.rows[0].status,'complete');
  const original=shared.documents.find(doc=>doc.name==='УПД-41.txt');
  shared.documents.push({name:'УПД-41-v2.txt',text:original.text+'\nКопия другой редакции'});
  first.amount='960000';
  const versions=await vm.runInContext('analyzeDemo(shared)',context);
  assert.equal(versions.issues[0].code,'AMBIGUOUS_PRIMARY');
  assert.equal(versions.issues[0].evidence.length,2);
  const model=JSON.parse(fs.readFileSync(path.join(__dirname,'../model/scenarios.json'),'utf8'));
  assert.deepEqual(JSON.parse(JSON.stringify(vm.runInContext('economicsDemo({}).inputs',context))),model.moderate.inputs);
  assert.equal(initial.profile_version,'supply-v1.1');
  const wrong = structuredClone(context.window.INITIAL_PACKET);
  wrong.profile='unknown-profile'; context.wrong=wrong;
  await assert.rejects(vm.runInContext("localApi('/api/analyze', wrong)",context));
  console.log('PASS: actual browser engine, initial/corrected packets, approval guard, invalid profile');
})().catch(error=>{ console.error(error); process.exitCode=1; });
